function hash(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) h = Math.imul(h ^ str.charCodeAt(i), 16777619);
  return h >>> 0;
}

/** 3 задания на день — одинаковые в течение дня */
export function tasksForDay(day: string, source: DailyTask[] = TASK_POOL): DailyTask[] {
  const pool = [...source];
  const out: DailyTask[] = [];
  let h = hash(day);
  while (out.length < 3 && pool.length) {
    const i = h % pool.length;
    out.push(pool.splice(i, 1)[0]);
    h = hash(String(h));
  }
  return out;
}

export function isTaskDone(s: AppState, task: DailyTask, day: string): boolean {
  if ((s.learning.doneTasks[day] ?? []).includes(task.id)) return true;
  return task.auto ? task.auto(s, day) : false;
}

